"""Task 029 (PRD requirement I.2's content, filed in `tasks.json` under the
label "I.1"): the task-boundary layer of the git-sink bound (#210).

`redact.py` scrubs known secret VALUES from everything the engine persists
or serves -- output, events, logs. A git commit the worker writes and
pushes is neither: nothing on that path ever runs a commit's message or
diff content through `redact.scrub_text`. This module is that missing
scrub, applied to "the commits this run created" at the task boundary --
i.e. the range between a `before` HEAD (read immediately before a worker
iteration is spawned, `loop.py`'s own `head_before`) and an `after` HEAD
(read immediately once it returns, `head_after`), the exact bracketing
`LoopSupervisor._step_worker` already takes for progress-witness purposes
(`_workspace_head_sha`).

Three things matter to callers:

- `scan_commits_for_secrets` -- the pure detector. VALUE matching only
  (PRD requirement I.4): a plain substring test against a `value -> label`
  map (the same shape `redact.build_redaction_map()` returns), never a
  regex over a "looks like a token" shape. A diff or doc that merely
  discusses a token's shape, or a fixture holding a synthetic
  token-SHAPED string that is not itself a configured value, never
  matches -- only the literal value does.
- `push_if_clean` -- the gate. Scans first; only when the scan comes back
  clean does it ever start a `git push` subprocess. On a hit, no push
  subprocess is started at all -- not with a warning, not with a
  disclosure (PRD requirement I.2) -- and the returned refusal text names
  the secret's variable NAME only, never the source prefix and never the
  matched value itself (the same bound I.1's hook layer states for
  itself, task 031).
- `install_push_gate` -- reached from git's own `pre-push`, `commit-msg`
  and `pre-commit` hooks through an engine-owned `core.hooksPath` OUTSIDE
  the workspace (task 031, PRD requirement I.1). `pre-push` is what makes
  "on a hit the run does not push" true of the run as a whole and not
  merely of the engine's own push subprocess: under the shipped division
  of labour (`JobConfig.workspace_push_remote is None`) the WORKER pushes
  from its own shell, DURING the iteration, long before the boundary read
  of `head_after` happens -- so a gate that only guards the engine's own
  `git push` would watch the leak leave over its shoulder. `commit-msg`
  and `pre-commit` catch the same class of hit one step earlier, before a
  leaking commit is even created locally -- a strictly narrower bound,
  since `git commit --no-verify` (and `--no-verify` on the push itself)
  bypasses all three, which is precisely why the task-boundary layer above
  exists and still records the hit either way. Every hook is generated by
  the engine, lives in the run directory (not the workspace, where the
  agent could rewrite it), and runs the very same detector; on a hit it
  exits non-zero and git refuses the commit or the push, printing a
  refusal that names the variable NAME only, never the matched value.

Fails OPEN on a read it cannot complete (no `git`, not a repository, an
unreadable commit) -- the same posture `loop.py`'s sibling helpers
(`_workspace_head_sha`, `_workspace_diff_paths`) already take for an
advisory git read: an unreadable scan is a defect to go fix, never a
silent reason to block every push forever. It never touches the redaction
map's own storage or the live in-memory map by itself -- callers pass
`secrets`, or leave it to default to `redact.build_redaction_map()`.

One authoritative exception (task cure-01-01, PRD requirement I.2, DoD 9):
the `pre-push` hook process is a NEW process every push, and it inherits
whatever environment the `git push` that triggered it was given, not the
engine's -- a worker can push with a secret's env var already stripped
from its own shell while the value is still live in the engine. So
`install_push_gate` also snapshots `redact.live_redaction_map()`, at
install time, as KEYED HASHES ONLY (never the raw values -- every run-dir
file, including this hooks dir, is scanned elsewhere for the literal
secret and must never contain it) into an engine-owned, 0o644 (root-owned
under task cure-01-02's uid boundary, but agent-READABLE -- the hook
process that reads it back runs at the agent uid; only WRITE is what the
boundary denies), never-printed-VALUE pair of files next to the hooks
(`KNOWN_SECRETS_FILENAME`, `KNOWN_SECRETS_PEPPER_FILENAME`), and only the
`pre-push` mode of
`hook_main` reads it back as a fallback once its own fresh
`build_redaction_map()` finds nothing -- so the push bound stays
authoritative regardless of the pushing process's own environment, without
ever putting a secret value on disk.
"""

