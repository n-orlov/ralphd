# The hook git itself runs before it transfers anything to a remote, the
# file the engine writes the boundary's own base sha into next to it, and
# the env var that overrides that file (tests, and a future caller that
# would rather not write the sha to disk at all).
PUSH_GATE_HOOK_NAME = "pre-push"
# Task 031 (PRD requirement I.1, #210): the earlier, LOCAL half of the same
# bound -- a commit is refused before it is even created, rather than only
# when it is pushed. Both live in the very same engine-owned hooks dir
# `install_push_gate` writes `PUSH_GATE_HOOK_NAME` into; git finds any hook
# by name in whatever directory `core.hooksPath` names, so no second
# `core.*` write is needed.
COMMIT_MSG_HOOK_NAME = "commit-msg"
PRE_COMMIT_HOOK_NAME = "pre-commit"
SCAN_BASE_FILENAME = "scan-base"
BASE_ENV_VAR = "RALPHD_COMMIT_SCAN_BASE"
# Task cure-01-01 (PRD requirement I.2, DoD 9, #210): the pre-push hook is a
# NEW process every time git invokes it, and it inherits whatever environment
# the `git push` that triggered it was given -- which, under the shipped
# division of labour, is the WORKER's own shell, not the engine's. A worker
# can push with an environment that no longer carries a secret's env var (it
# was already forwarded, used, and popped, or simply never present in that
# particular shell) while the value is still perfectly live in the ENGINE's
# own `redact.live_redaction_map()` -- rebuilding fresh from `os.environ`
# inside the hook process at push time then finds nothing, and the leak
# reaches the remote. The authoritative bound cannot depend on the pushing
# process's own environment, so `install_push_gate` snapshots the engine's
# live map at install time -- but NEVER as the raw values (every run-dir
# file, including this hooks dir, is scanned by `tests/test_secret_redaction.py`
# for the literal secret and must never contain it): what is written to disk
# is a per-length table of KEYED HASHES (`hmac.new(pepper, value,
# sha256).hexdigest()`, `pepper` a fresh 32 random bytes generated at the
# same install and stored next to it, both files 0o644, root-owned but
# agent-readable under task cure-01-02's boundary) mapping digest ->
# label. The hook process re-derives the same digest over every
# same-length window of a commit's message/diff and looks it up -- it never
# recovers or needs the value itself, only whether ITS digest is a member of
# the known set, so the file leaks no more than the SET OF LENGTHS of
# engine-known secrets, never a value. Read back only by the hook process
# itself (`_hashed_snapshot_from`), merged with whatever
# `build_redaction_map()`'s literal match can still see from its own
# environment, so a value only reachable through the ENGINE's process
# (creds files, `PUT /config/llm` overrides, an env var the push-time shell
# no longer carries) is caught exactly as authoritatively as one still
# visible to the hook's own rebuild -- without ever putting the value on
# disk.
KNOWN_SECRETS_FILENAME = "known-secrets"
KNOWN_SECRETS_PEPPER_FILENAME = "known-secrets-pepper"
_PEPPER_BYTES = 32

# Task cure-01-03 (PRD requirement I.3, DoD 9, #210): a `commit-msg`/
# `pre-commit` hit refuses the commit BEFORE it is ever created, so no new
# commit lands between a task boundary's `head_before` and `head_after` for
# `_scan_task_boundary_commits` to find -- I.3's fault-and-pause consequence
# would otherwise never fire for this earlier, narrower catch, only for the
# authoritative one. `hook_main` writes this JSON marker (mode, part,
# variable NAME only -- never the matched value, never a sha, since no
# commit exists yet) into `hit_marker_dir` on exactly that refusal;
# `read_and_clear_hook_hit_marker` is the engine's own read-once side of it,
# called once per worker iteration after the boundary scan. `hit_marker_dir`
# is deliberately NOT `hooks_dir`: under the real uid boundary (task
# cure-01-02) `hooks_dir` is root-owned 0o755 with no write bit for the
# agent uid, so a hook process running at the agent uid could never create a
# new entry there -- `hit_marker_dir` is the run directory instead, which
# the agent uid already writes notes.md and artifacts into either way, so
# writing this marker needs no new permission and no new sink.
HOOK_HIT_MARKER_FILENAME = "commit-scan-hook-hit.json"


def _write_hook_hit_marker(hit_marker_dir, mode: str, hit: dict) -> None:
    """Best-effort: a marker the hook process could not write is a defect
    to go fix, never a reason to raise out of the hook and leave the
    refusal itself undelivered (the same advisory-read posture every other
    helper in this module takes for a git read it cannot complete).
    """
    try:
        directory = Path(hit_marker_dir)
        directory.mkdir(parents=True, exist_ok=True)
        record = {"mode": mode, "part": hit.get("part"),
                 "variable": hit.get("variable")}
        path = directory / HOOK_HIT_MARKER_FILENAME
        tmp = path.with_suffix(path.suffix + ".tmp")
        tmp.write_text(json.dumps(record))
        os.replace(tmp, path)
    except OSError:
        pass


def read_and_clear_hook_hit_marker(hit_marker_dir) -> dict | None:
    """The engine's own side of `_write_hook_hit_marker`: read the marker a
    `commit-msg`/`pre-commit` refusal may have left in `hit_marker_dir` for
    THIS iteration, and remove it either way -- read-once, so a stale
    marker from an earlier iteration (one whose commit later succeeded on
    a later, clean attempt, or whose task moved on before an operator ever
    looked) is never replayed against a later iteration that never hit
    anything at all. Returns `None` on a missing file, an unreadable one,
    or malformed JSON -- the same fail-open posture as every other read
    here; a hit that could not be conveyed this way is still a real
    refusal (git already exited non-zero and nothing was committed), just
    one this particular channel could not carry.
    """
    path = Path(hit_marker_dir) / HOOK_HIT_MARKER_FILENAME
    try:
        raw = path.read_text()
    except OSError:
        return None
    finally:
        try:
            path.unlink(missing_ok=True)
        except OSError:
            pass
    try:
        record = json.loads(raw)
    except ValueError:
        return None
    if not isinstance(record, dict) or not record.get("variable"):
        return None
    return record


_ZERO_SHA_CHARS = {"0"}


def _new_pepper() -> bytes:
    return os.urandom(_PEPPER_BYTES)


def _hmac_hex(pepper: bytes, value: str) -> str:
    return hmac.new(pepper, value.encode("utf-8", "surrogateescape"),
                    hashlib.sha256).hexdigest()


def _digest_snapshot(pepper: bytes, secrets: dict[str, str]) -> dict[str, dict[str, str]]:
    """`{str(len(value)): {hexdigest: label}}` for every `value` in
    `secrets` -- never the value itself, and never the label's value half,
    only its NAME half is ever surfaced (`_variable_name`, at lookup time).
    """
    by_len: dict[str, dict[str, str]] = {}
    for value, label in secrets.items():
        if not value:
            continue
        by_len.setdefault(str(len(value)), {})[_hmac_hex(pepper, value)] = label
    return by_len


def _scan_text_for_hashed_secrets(text: str, pepper: bytes,
                                  digests: dict[str, dict[str, str]]) -> str | None:
    """The label for the first keyed-hash match of any known length's
    digest set against a sliding window of `text`, or `None`. Brute-force
    (no rolling hash): the lengths involved and the text sizes this scans
    (a single commit's message or diff) are both small enough that this
    never needs to be fast."""
    if not text or not digests:
        return None
    for length_str, digest_map in digests.items():
        try:
            length = int(length_str)
        except ValueError:
            continue
        if length <= 0 or length > len(text):
            continue
        for i in range(len(text) - length + 1):
            label = digest_map.get(_hmac_hex(pepper, text[i:i + length]))
            if label is not None:
                return label
    return None


def scan_commits_for_hashed_secrets(workspace, base_sha: str | None, head_sha: str,
                                    pepper: bytes | None,
                                    digests: dict[str, dict[str, str]] | None) -> dict | None:
    """`scan_commits_for_secrets`'s keyed-hash counterpart: the same
    message-then-diff, oldest-commit-first walk over `commits_between`, but
    matching against a digest table instead of literal values -- the layer
    that survives a push-time process whose own environment no longer
    carries the secret (task cure-01-01, PRD requirement I.2, DoD 9).
    """
    if not pepper or not digests:
        return None
    for sha in commits_between(workspace, base_sha, head_sha):
        label = _scan_text_for_hashed_secrets(
            commit_message(workspace, sha), pepper, digests)
        if label is not None:
            return {"sha": sha, "part": "message", "variable": _variable_name(label)}
        label = _scan_text_for_hashed_secrets(
            commit_diff(workspace, sha), pepper, digests)
        if label is not None:
            return {"sha": sha, "part": "diff", "variable": _variable_name(label)}
    return None


def _run_git(workspace, *args: str, timeout: float = _GIT_TIMEOUT_S,
            safe_directory: str | None = None):
    """`safe_directory`, when given, adds one `-c safe.directory=<value>`
    ahead of `-C` -- a per-INVOCATION exception (no file written, nothing
    persisted) to git's own "detected dubious ownership" refusal, which
    fires whenever the calling process's effective uid differs from the
    repository directory's owner (git >= 2.35.2). `install_push_gate`
    passes this only when it detects exactly that mismatch (task
    cure-01-01-2, review finding R2 upheld): under the real uid boundary
    this function's own caller runs at effective uid 0 (root, via
    `privsep.root_for_write()`) against a workspace the AGENT uid owns,
    which is precisely the case the CI workflow's own "Trust the checked-
    out workspace (container root != host checkout owner)" step
    (`.github/workflows/gate.yml`) exists to clear, in the opposite
    direction. Without it every git call below returns nonzero and
    `install_push_gate` degrades to `None` -- gate not installed, silently.
    """
    try:
        cmd = ["git"]
        if safe_directory is not None:
            cmd += ["-c", f"safe.directory={safe_directory}"]
        cmd += ["-C", str(workspace), *args]
        return subprocess.run(
            cmd, capture_output=True, text=True, timeout=timeout)
    except OSError:
        return None


def commits_between(workspace, base_sha: str | None, head_sha: str) -> list[str]:
    """Commit shas strictly after `base_sha` up to and including
    `head_sha`, oldest first. `base_sha=None` (no prior boundary -- the
    workspace's very first task) scans every ancestor of `head_sha`.
    Empty list, never `None`, on any read failure -- the caller's loop
    over an empty list is trivially a no-hit, which is the fail-open
    posture this whole module keeps."""
    if not head_sha:
        return []
    rev_range = f"{base_sha}..{head_sha}" if base_sha else head_sha
    result = _run_git(workspace, "log", "--format=%H", "--reverse", rev_range)
    if result is None or result.returncode != 0:
        return []
    return [line for line in result.stdout.splitlines() if line]


def commit_message(workspace, sha: str) -> str:
    result = _run_git(workspace, "log", "-1", "--format=%B", sha)
    if result is None or result.returncode != 0:
        return ""
    return result.stdout


def commit_diff(workspace, sha: str) -> str:
    """The full patch this single commit introduced -- `--no-renames` (the
    same rationale `_workspace_diff_paths` documents) so a renamed-away
    file's own old content, not only the rename pair, is still scanned."""
    result = _run_git(
        workspace, "show", "--no-color", "--format=", "--no-renames", sha)
    if result is None or result.returncode != 0:
        return ""
    return result.stdout


def scan_text_for_secrets(text: str, secrets: dict[str, str] | None = None, *,
                          part: str = "message") -> dict | None:
    """The same VALUE-only match `scan_commits_for_secrets` runs over a
    commit already made, applied to a single blob of text that has no sha
    yet -- a not-yet-committed message (`commit-msg`) or a staged diff
    (`pre-commit`). Returns `None` on no hit or empty input; on a hit,
    `{"sha": None, "part": part, "variable": <name>}` -- the same shape
    `scan_commits_for_secrets` returns, minus the sha it does not have.
    """
    if secrets is None:
        secrets = redact.build_redaction_map()
    if not secrets or not text:
        return None
    for value, label in sorted(secrets.items(), key=lambda kv: -len(kv[0])):
        if value and value in text:
            return {"sha": None, "part": part, "variable": _variable_name(label)}
    return None


def _variable_name(label: str) -> str:
    """The variable NAME half of a redaction-map label. `redact.py`'s
    `value -> label` map spells labels `"env:NAME"`, `"<file>.env:NAME"`,
    `"models.json:NAME"`, etc; the refusal text names only the part after
    the last `:` -- never the source prefix, and never the value."""
    if not label:
        return label
    return label.rsplit(":", 1)[-1]


def scan_commits_for_secrets(workspace, base_sha: str | None, head_sha: str,
                             secrets: dict[str, str] | None = None) -> dict | None:
    """Scan every commit in `commits_between(base_sha, head_sha)`, message
    THEN diff, for a VALUE match against `secrets` (defaults to
    `redact.build_redaction_map()`, memory-only, never persisted).

    Returns `None` on no hit. On a hit, returns the FIRST one found
    (oldest commit first, message before that same commit's diff):
    `{"sha": <full sha>, "part": "message" | "diff", "variable": <name>}`.
    """
    if secrets is None:
        secrets = redact.build_redaction_map()
    if not secrets:
        return None
    items = sorted(secrets.items(), key=lambda kv: -len(kv[0]))
    for sha in commits_between(workspace, base_sha, head_sha):
        message = commit_message(workspace, sha)
        for value, label in items:
            if value and value in message:
                return {"sha": sha, "part": "message",
                        "variable": _variable_name(label)}
        diff = commit_diff(workspace, sha)
        for value, label in items:
            if value and value in diff:
                return {"sha": sha, "part": "diff",
                        "variable": _variable_name(label)}
    return None


def refusal_text(hit: dict) -> str:
    """The refusal's own text. Names the variable only -- never the
    matched value (PRD requirement I.1/I.2's shared bound)."""
    sha = str(hit.get("sha", ""))[:12]
    return (
        f"refusing to push: commit {sha}'s {hit.get('part')} matches a "
        f"known secret value for variable {hit.get('variable')!r}"
    )


def commit_refusal_text(hit: dict) -> str:
    """The `commit-msg`/`pre-commit` hooks' own refusal text -- no sha
    exists yet (the commit these hooks run against is not made), so unlike
    `refusal_text` this never tries to name one. Same bound: the variable
    name only, never the matched value."""
    return (
        f"refusing to commit: the {hit.get('part')} matches a known secret "
        f"value for variable {hit.get('variable')!r}"
    )


