"""Task 029 (PRD requirement I.2's content, filed in `tasks.json` under the
label "I.1"): the task-boundary layer of the git-sink bound (#210).

`redact.py` scrubs known secret VALUES from everything the engine persists
or serves -- output, events, logs. A git commit the worker writes and
pushes is neither: nothing on that path ever runs a commit's message or
diff content through `redact.scrub_text`. This module is that missing
scrub, applied to "the commits this run created" at the task boundary --
i.e. the range between a `before` HEAD (read immediately before a worker
iteration is spawned, `loop.py`'s own `head_before`) and an `after` HEAD
(read immediately once it returns, `head_after`), the exact bracketing
`LoopSupervisor._step_worker` already takes for progress-witness purposes
(`_workspace_head_sha`).

Three things matter to callers:

- `scan_commits_for_secrets` -- the pure detector. VALUE matching only
  (PRD requirement I.4): a plain substring test against a `value -> label`
  map (the same shape `redact.build_redaction_map()` returns), never a
  regex over a "looks like a token" shape. A diff or doc that merely
  discusses a token's shape, or a fixture holding a synthetic
  token-SHAPED string that is not itself a configured value, never
  matches -- only the literal value does.
- `push_if_clean` -- the gate. Scans first; only when the scan comes back
  clean does it ever start a `git push` subprocess. On a hit, no push
  subprocess is started at all -- not with a warning, not with a
  disclosure (PRD requirement I.2) -- and the returned refusal text names
  the secret's variable NAME only, never the source prefix and never the
  matched value itself (the same bound I.1's hook layer states for
  itself, task 031).
- `install_push_gate` -- reached from git's own `pre-push`, `commit-msg`
  and `pre-commit` hooks through an engine-owned `core.hooksPath` OUTSIDE
  the workspace (task 031, PRD requirement I.1). `pre-push` is what makes
  "on a hit the run does not push" true of the run as a whole and not
  merely of the engine's own push subprocess: under the shipped division
  of labour (`JobConfig.workspace_push_remote is None`) the WORKER pushes
  from its own shell, DURING the iteration, long before the boundary read
  of `head_after` happens -- so a gate that only guards the engine's own
  `git push` would watch the leak leave over its shoulder. `commit-msg`
  and `pre-commit` catch the same class of hit one step earlier, before a
  leaking commit is even created locally -- a strictly narrower bound,
  since `git commit --no-verify` (and `--no-verify` on the push itself)
  bypasses all three, which is precisely why the task-boundary layer above
  exists and still records the hit either way. Every hook is generated by
  the engine, lives in the run directory (not the workspace, where the
  agent could rewrite it), and runs the very same detector; on a hit it
  exits non-zero and git refuses the commit or the push, printing a
  refusal that names the variable NAME only, never the matched value.

Fails OPEN on a read it cannot complete (no `git`, not a repository, an
unreadable commit) -- the same posture `loop.py`'s sibling helpers
(`_workspace_head_sha`, `_workspace_diff_paths`) already take for an
advisory git read: an unreadable scan is a defect to go fix, never a
silent reason to block every push forever. It never touches the redaction
map's own storage or the live in-memory map by itself -- callers pass
`secrets`, or leave it to default to `redact.build_redaction_map()`.
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

from . import redact

_GIT_TIMEOUT_S = 30

# The hook git itself runs before it transfers anything to a remote, the
# file the engine writes the boundary's own base sha into next to it, and
# the env var that overrides that file (tests, and a future caller that
# would rather not write the sha to disk at all).
PUSH_GATE_HOOK_NAME = "pre-push"
# Task 031 (PRD requirement I.1, #210): the earlier, LOCAL half of the same
# bound -- a commit is refused before it is even created, rather than only
# when it is pushed. Both live in the very same engine-owned hooks dir
# `install_push_gate` writes `PUSH_GATE_HOOK_NAME` into; git finds any hook
# by name in whatever directory `core.hooksPath` names, so no second
# `core.*` write is needed.
COMMIT_MSG_HOOK_NAME = "commit-msg"
PRE_COMMIT_HOOK_NAME = "pre-commit"
SCAN_BASE_FILENAME = "scan-base"
BASE_ENV_VAR = "RALPHD_COMMIT_SCAN_BASE"

_ZERO_SHA_CHARS = {"0"}


def _run_git(workspace, *args: str, timeout: float = _GIT_TIMEOUT_S):
    try:
        return subprocess.run(
            ["git", "-C", str(workspace), *args],
            capture_output=True, text=True, timeout=timeout)
    except OSError:
        return None


def commits_between(workspace, base_sha: str | None, head_sha: str) -> list[str]:
    """Commit shas strictly after `base_sha` up to and including
    `head_sha`, oldest first. `base_sha=None` (no prior boundary -- the
    workspace's very first task) scans every ancestor of `head_sha`.
    Empty list, never `None`, on any read failure -- the caller's loop
    over an empty list is trivially a no-hit, which is the fail-open
    posture this whole module keeps."""
    if not head_sha:
        return []
    rev_range = f"{base_sha}..{head_sha}" if base_sha else head_sha
    result = _run_git(workspace, "log", "--format=%H", "--reverse", rev_range)
    if result is None or result.returncode != 0:
        return []
    return [line for line in result.stdout.splitlines() if line]


def commit_message(workspace, sha: str) -> str:
    result = _run_git(workspace, "log", "-1", "--format=%B", sha)
    if result is None or result.returncode != 0:
        return ""
    return result.stdout


def commit_diff(workspace, sha: str) -> str:
    """The full patch this single commit introduced -- `--no-renames` (the
    same rationale `_workspace_diff_paths` documents) so a renamed-away
    file's own old content, not only the rename pair, is still scanned."""
    result = _run_git(
        workspace, "show", "--no-color", "--format=", "--no-renames", sha)
    if result is None or result.returncode != 0:
        return ""
    return result.stdout


def scan_text_for_secrets(text: str, secrets: dict[str, str] | None = None, *,
                          part: str = "message") -> dict | None:
    """The same VALUE-only match `scan_commits_for_secrets` runs over a
    commit already made, applied to a single blob of text that has no sha
    yet -- a not-yet-committed message (`commit-msg`) or a staged diff
    (`pre-commit`). Returns `None` on no hit or empty input; on a hit,
    `{"sha": None, "part": part, "variable": <name>}` -- the same shape
    `scan_commits_for_secrets` returns, minus the sha it does not have.
    """
    if secrets is None:
        secrets = redact.build_redaction_map()
    if not secrets or not text:
        return None
    for value, label in sorted(secrets.items(), key=lambda kv: -len(kv[0])):
        if value and value in text:
            return {"sha": None, "part": part, "variable": _variable_name(label)}
    return None


def _variable_name(label: str) -> str:
    """The variable NAME half of a redaction-map label. `redact.py`'s
    `value -> label` map spells labels `"env:NAME"`, `"<file>.env:NAME"`,
    `"models.json:NAME"`, etc; the refusal text names only the part after
    the last `:` -- never the source prefix, and never the value."""
    if not label:
        return label
    return label.rsplit(":", 1)[-1]


def scan_commits_for_secrets(workspace, base_sha: str | None, head_sha: str,
                             secrets: dict[str, str] | None = None) -> dict | None:
    """Scan every commit in `commits_between(base_sha, head_sha)`, message
    THEN diff, for a VALUE match against `secrets` (defaults to
    `redact.build_redaction_map()`, memory-only, never persisted).

    Returns `None` on no hit. On a hit, returns the FIRST one found
    (oldest commit first, message before that same commit's diff):
    `{"sha": <full sha>, "part": "message" | "diff", "variable": <name>}`.
    """
    if secrets is None:
        secrets = redact.build_redaction_map()
    if not secrets:
        return None
    items = sorted(secrets.items(), key=lambda kv: -len(kv[0]))
    for sha in commits_between(workspace, base_sha, head_sha):
        message = commit_message(workspace, sha)
        for value, label in items:
            if value and value in message:
                return {"sha": sha, "part": "message",
                        "variable": _variable_name(label)}
        diff = commit_diff(workspace, sha)
        for value, label in items:
            if value and value in diff:
                return {"sha": sha, "part": "diff",
                        "variable": _variable_name(label)}
    return None


def refusal_text(hit: dict) -> str:
    """The refusal's own text. Names the variable only -- never the
    matched value (PRD requirement I.1/I.2's shared bound)."""
    sha = str(hit.get("sha", ""))[:12]
    return (
        f"refusing to push: commit {sha}'s {hit.get('part')} matches a "
        f"known secret value for variable {hit.get('variable')!r}"
    )


def commit_refusal_text(hit: dict) -> str:
    """The `commit-msg`/`pre-commit` hooks' own refusal text -- no sha
    exists yet (the commit these hooks run against is not made), so unlike
    `refusal_text` this never tries to name one. Same bound: the variable
    name only, never the matched value."""
    return (
        f"refusing to commit: the {hit.get('part')} matches a known secret "
        f"value for variable {hit.get('variable')!r}"
    )


# ---------------------------------------------------------------------------
# The push gate reached from git's own `pre-push` hook.
# ---------------------------------------------------------------------------


def _resolves(workspace, sha: str) -> bool:
    if not sha or set(sha) == _ZERO_SHA_CHARS:
        return False
    result = _run_git(workspace, "cat-file", "-e", f"{sha}^{{commit}}")
    return result is not None and result.returncode == 0


def _first_parent(workspace, sha: str) -> str | None:
    result = _run_git(workspace, "rev-parse", "-q", "--verify", f"{sha}^")
    if result is None or result.returncode != 0:
        return None
    return result.stdout.strip() or None


def _scan_base(workspace, remote_sha: str, local_sha: str,
               base_sha: str | None) -> str | None:
    """Which base the pre-push gate scans this ref from, most precise
    first:

    1. the remote's own current tip for that ref, when the remote HAS one
       and this repository can read it -- exactly "the commits this push
       would add";
    2. the boundary base the engine recorded (`scan-base` / `BASE_ENV_VAR`)
       -- "the commits this run created", for a first push to a remote
       with no such ref yet;
    3. `local_sha`'s first parent -- the pushed tip alone.

    (3) is deliberately narrow rather than "every ancestor": this
    repository's own history contains real historically-leaked commits
    whose remediation is explicitly out of scope (PRD requirement I.10),
    and a full-ancestry scan on a fresh remote would refuse every push
    forever over commits no task of this wave may touch. A root commit
    has no parent, so `None` there means "this one commit" anyway.
    """
    if _resolves(workspace, remote_sha):
        return remote_sha
    if base_sha and _resolves(workspace, base_sha):
        return base_sha
    return _first_parent(workspace, local_sha)


def gate_push_refs(workspace, lines, *, secrets: dict[str, str] | None = None,
                   base_sha: str | None = None) -> dict | None:
    """Scan every ref a `pre-push` invocation is trying to advance.

    `lines` is git's own stdin for that hook: `<local ref> <local sha>
    <remote ref> <remote sha>` per line. Returns the first hit (same shape
    `scan_commits_for_secrets` returns) or `None`. A ref DELETION (an
    all-zero local sha) transfers no objects and is skipped.
    """
    if secrets is None:
        secrets = redact.build_redaction_map()
    if not secrets:
        return None
    for raw in lines:
        parts = str(raw).split()
        if len(parts) < 4:
            continue
        _local_ref, local_sha, _remote_ref, remote_sha = parts[:4]
        if not local_sha or set(local_sha) == _ZERO_SHA_CHARS:
            continue
        hit = scan_commits_for_secrets(
            workspace, _scan_base(workspace, remote_sha, local_sha, base_sha),
            local_sha, secrets=secrets)
        if hit is not None:
            return hit
    return None


def _hook_script(mode: str, python: str, pkg_parent: str) -> str:
    return (
        "#!/bin/sh\n"
        f"# ralphd's task-boundary git-sink gate ({mode}) "
        "(PRD requirement I.1/I.2, #210).\n"
        "# GENERATED by ralphd.engine.commit_scan.install_push_gate -- it lives\n"
        "# in the run directory, owned by the engine, OUTSIDE the workspace, so\n"
        "# the agent uid cannot rewrite the bound it is subject to. Do not edit.\n"
        f"PYTHONPATH=\"{pkg_parent}${{PYTHONPATH:+:$PYTHONPATH}}\"\n"
        "export PYTHONPATH\n"
        f"exec \"{python}\" -m ralphd.engine.commit_scan {mode} "
        "--hooks-dir \"$(dirname \"$0\")\" \"$@\"\n"
    )


# Every hook this module installs, in the one hooks dir `core.hooksPath`
# names: `PUSH_GATE_HOOK_NAME` first so callers that only want "the
# push gate's own path" (the pre-031 contract `install_push_gate` already
# had callers for) keep getting exactly that path back.
_ALL_HOOK_NAMES = (PUSH_GATE_HOOK_NAME, COMMIT_MSG_HOOK_NAME, PRE_COMMIT_HOOK_NAME)


def install_push_gate(workspace, hooks_dir, *, base_sha: str | None = None,
                      python: str | None = None) -> Path | None:
    """Install (or refresh) the `pre-push`, `commit-msg` and `pre-commit`
    gates for `workspace` and point the repository's `core.hooksPath` at
    `hooks_dir` -- one write reaches all three, since git looks up every
    hook by name inside whatever directory `core.hooksPath` names.

    `hooks_dir` belongs to the ENGINE and must not be inside the workspace
    -- a hook the worker can edit is not a bound (the same privsep
    reasoning v0.22's A/B/C states, and PRD requirement I.1's own wording).
    Every hook file is written 0o755 and the directory 0o755: readable and
    executable by the agent uid, writable by neither it nor its group.

    `base_sha` is the boundary base the engine just read (`head_before`);
    it is written next to the hooks as `scan-base` so a first push to a
    remote that has no such ref yet still scans exactly "the commits this
    run created" and not the whole of history. It is a SHA, never a secret.
    `commit-msg`/`pre-commit` never read it -- they scan a single
    not-yet-committed blob of text, not a commit range.

    Returns the `pre-push` hook's path (the historical return value, task
    029's own callers key off it), or `None` when the repository's config
    could not be written (no `git`, not a repository) -- the same
    advisory-read posture the rest of this module keeps; the task-boundary
    scan still runs either way.
    """
    hooks_dir = Path(hooks_dir)
    hooks_dir.mkdir(parents=True, exist_ok=True)
    os.chmod(hooks_dir, 0o755)
    pkg_parent = str(Path(__file__).resolve().parents[2])
    python = python or sys.executable
    push_hook = None
    for name in _ALL_HOOK_NAMES:
        path = hooks_dir / name
        path.write_text(_hook_script(name, python, pkg_parent))
        os.chmod(path, 0o755)
        if name == PUSH_GATE_HOOK_NAME:
            push_hook = path
    base_file = hooks_dir / SCAN_BASE_FILENAME
    base_file.write_text(f"{base_sha or ''}\n")
    os.chmod(base_file, 0o644)
    result = _run_git(workspace, "config", "core.hooksPath", str(hooks_dir))
    if result is None or result.returncode != 0:
        return None
    return push_hook


def _base_from(hooks_dir: str | None) -> str | None:
    env_base = os.environ.get(BASE_ENV_VAR, "").strip()
    if env_base:
        return env_base
    if not hooks_dir:
        return None
    try:
        return (Path(hooks_dir) / SCAN_BASE_FILENAME).read_text().strip() or None
    except OSError:
        return None


def _toplevel(default: Path) -> Path:
    result = _run_git(default, "rev-parse", "--show-toplevel")
    if result is None or result.returncode != 0:
        return default
    top = result.stdout.strip()
    return Path(top) if top else default


def hook_main(argv: list[str] | None = None, stdin=None) -> int:
    """The generated hooks' own entry point (`python -m
    ralphd.engine.commit_scan <mode> --hooks-dir <dir> ...`), `<mode>` one
    of `pre-push`, `commit-msg`, `pre-commit` -- the first positional arg,
    which is also each hook's own filename (`_ALL_HOOK_NAMES`).

    Rebuilds the redaction map in THIS process (`build_redaction_map`)
    rather than being handed values: a hook file or an argv carrying secret
    VALUES would itself be a new sink, which is the whole defect being
    fixed. Exit 1 (git refuses the commit or the push) on a hit, printing a
    refusal that names the variable NAME only -- never the matched value.
    Exit 0 on no hit, on an unrecognised mode, and on any read it could not
    complete (fail open; the task-boundary layer is the authoritative one).
    """
    argv = list(sys.argv[1:] if argv is None else argv)
    if not argv:
        return 0
    mode, rest = argv[0], list(argv[1:])
    hooks_dir = None
    if "--hooks-dir" in rest:
        i = rest.index("--hooks-dir")
        if i + 1 < len(rest):
            hooks_dir = rest[i + 1]
            del rest[i:i + 2]
    workspace = _toplevel(Path.cwd())
    base_sha = _base_from(hooks_dir)

    if mode == PUSH_GATE_HOOK_NAME:
        stream = sys.stdin if stdin is None else stdin
        try:
            lines = stream.read().splitlines()
        except (OSError, ValueError):
            return 0
        hit = gate_push_refs(workspace, lines, base_sha=base_sha)
        if hit is None:
            return 0
        print(refusal_text(hit), file=sys.stderr)
        return 1

    if mode == COMMIT_MSG_HOOK_NAME:
        # git's own arg to `commit-msg`: the path of the file holding the
        # message the agent is about to commit.
        if not rest:
            return 0
        try:
            text = Path(rest[0]).read_text()
        except OSError:
            return 0
        hit = scan_text_for_secrets(text, part="message")
        if hit is None:
            return 0
        print(commit_refusal_text(hit), file=sys.stderr)
        return 1

    if mode == PRE_COMMIT_HOOK_NAME:
        # git's own `pre-commit` passes no args; the content to check is
        # whatever is staged.
        result = _run_git(workspace, "diff", "--cached", "--no-color",
                          "--no-renames")
        diff = result.stdout if result is not None and result.returncode == 0 else ""
        hit = scan_text_for_secrets(diff, part="diff")
        if hit is None:
            return 0
        print(commit_refusal_text(hit), file=sys.stderr)
        return 1

    return 0


def push_if_clean(workspace, base_sha: str | None, head_sha: str, *,
                  secrets: dict[str, str] | None = None,
                  remote: str = "origin", branch: str = "main",
                  timeout: float = _GIT_TIMEOUT_S):
    """The task-boundary gate. Scans first; a `git push` subprocess is
    started ONLY when the scan comes back clean -- on a hit, no push
    subprocess is ever started, not with a warning, not with a
    disclosure.

    Returns `(pushed: bool, hit: dict | None, refusal: str | None)`.
    """
    hit = scan_commits_for_secrets(workspace, base_sha, head_sha, secrets=secrets)
    if hit is not None:
        return False, hit, refusal_text(hit)
    subprocess.run(
        ["git", "-C", str(workspace), "push", remote, branch],
        capture_output=True, text=True, timeout=timeout)
    return True, None, None


if __name__ == "__main__":  # pragma: no cover - exercised as a real hook
    raise SystemExit(hook_main())
