def _resolves(workspace, sha: str) -> bool:
    if not sha or set(sha) == _ZERO_SHA_CHARS:
        return False
    result = _run_git(workspace, "cat-file", "-e", f"{sha}^{{commit}}")
    return result is not None and result.returncode == 0


def _first_parent(workspace, sha: str) -> str | None:
    result = _run_git(workspace, "rev-parse", "-q", "--verify", f"{sha}^")
    if result is None or result.returncode != 0:
        return None
    return result.stdout.strip() or None


def _scan_base(workspace, remote_sha: str, local_sha: str,
               base_sha: str | None) -> str | None:
    """Which base the pre-push gate scans this ref from, most precise
    first:

    1. the remote's own current tip for that ref, when the remote HAS one
       and this repository can read it -- exactly "the commits this push
       would add";
    2. the boundary base the engine recorded (`scan-base` / `BASE_ENV_VAR`)
       -- "the commits this run created", for a first push to a remote
       with no such ref yet;
    3. `local_sha`'s first parent -- the pushed tip alone.

    (3) is deliberately narrow rather than "every ancestor": this
    repository's own history contains real historically-leaked commits
    whose remediation is explicitly out of scope (PRD requirement I.10),
    and a full-ancestry scan on a fresh remote would refuse every push
    forever over commits no task of this wave may touch. A root commit
    has no parent, so `None` there means "this one commit" anyway.
    """
    if _resolves(workspace, remote_sha):
        return remote_sha
    if base_sha and _resolves(workspace, base_sha):
        return base_sha
    return _first_parent(workspace, local_sha)


def gate_push_refs(workspace, lines, *, secrets: dict[str, str] | None = None,
                   base_sha: str | None = None) -> dict | None:
    """Scan every ref a `pre-push` invocation is trying to advance.

    `lines` is git's own stdin for that hook: `<local ref> <local sha>
    <remote ref> <remote sha>` per line. Returns the first hit (same shape
    `scan_commits_for_secrets` returns) or `None`. A ref DELETION (an
    all-zero local sha) transfers no objects and is skipped.
    """
    if secrets is None:
        secrets = redact.build_redaction_map()
    if not secrets:
        return None
    for raw in lines:
        parts = str(raw).split()
        if len(parts) < 4:
            continue
        _local_ref, local_sha, _remote_ref, remote_sha = parts[:4]
        if not local_sha or set(local_sha) == _ZERO_SHA_CHARS:
            continue
        hit = scan_commits_for_secrets(
            workspace, _scan_base(workspace, remote_sha, local_sha, base_sha),
            local_sha, secrets=secrets)
        if hit is not None:
            return hit
    return None


def _hook_script(mode: str, python: str, pkg_parent: str,
                 hit_marker_dir) -> str:
    return (
        "#!/bin/sh\n"
        f"# ralphd's task-boundary git-sink gate ({mode}) "
        "(PRD requirement I.1/I.2, #210).\n"
        "# GENERATED by ralphd.engine.commit_scan.install_push_gate -- it lives\n"
        "# in the run directory, owned by the engine, OUTSIDE the workspace, so\n"
        "# the agent uid cannot rewrite the bound it is subject to. Do not edit.\n"
        f"PYTHONPATH=\"{pkg_parent}${{PYTHONPATH:+:$PYTHONPATH}}\"\n"
        "export PYTHONPATH\n"
        f"exec \"{python}\" -m ralphd.engine.commit_scan {mode} "
        "--hooks-dir \"$(dirname \"$0\")\" "
        f"--hit-marker-dir \"{hit_marker_dir}\" \"$@\"\n"
    )


# Every hook this module installs, in the one hooks dir `core.hooksPath`
# names: `PUSH_GATE_HOOK_NAME` first so callers that only want "the
# push gate's own path" (the pre-031 contract `install_push_gate` already
# had callers for) keep getting exactly that path back.
_ALL_HOOK_NAMES = (PUSH_GATE_HOOK_NAME, COMMIT_MSG_HOOK_NAME, PRE_COMMIT_HOOK_NAME)


def install_push_gate(workspace, hooks_dir, *, base_sha: str | None = None,
                      python: str | None = None,
                      secrets: dict[str, str] | None = None,
                      hit_marker_dir=None) -> Path | None:
    """Install (or refresh) the `pre-push`, `commit-msg` and `pre-commit`
    gates for `workspace` and point the repository's `core.hooksPath` at
    `hooks_dir` -- one write reaches all three, since git looks up every
    hook by name inside whatever directory `core.hooksPath` names.

    `hooks_dir` belongs to the ENGINE and must not be inside the workspace
    -- a hook the worker can edit is not a bound (the same privsep
    reasoning v0.22's A/B/C states, and PRD requirement I.1's own wording).
    Every hook file is written 0o555 and the `scan-base` note 0o444: readable
    and executable by the agent uid and carrying NO write bit at all, for the
    owner no less than for group and other, so a write attempt by the agent
    uid is refused by the kernel (EACCES) even where -- as in this run's own
    unprivileged test environment -- engine and agent share one uid and no
    real privsep boundary separates them. A refresh therefore REPLACES each
    file (unlink, write, chmod) instead of writing through it; the directory
    itself stays 0o755 so the engine can do exactly that.

    Task cure-01-02 (PRD requirement I.1, DoD 9, #210's R2 finding) closes
    the gap those file modes alone left open: a directory-entry operation
    (`unlink`/`rename`/`replace` of a NAME inside `hooks_dir`, or of
    `hooks_dir`'s own entry in ITS parent) is gated by the parent
    directory's permissions, never the target's, so an agent-owned
    `hooks_dir` was rewritable regardless of what mode its files carried.
    The caller (`LoopSupervisor._install_commit_scan_push_gate`) is
    responsible for passing a `hooks_dir` that is itself protected --
    `privsep.commit_scan_hooks_dir()` under the uid boundary, parented by
    the same root-owned `/var/lib/ralphd` the task record and run-secrets
    mount already rely on -- and for calling this function inside
    `privsep.root_for_write()` so every `mkdir`/`write`/`chmod` below
    actually lands root-owned. This function itself stays agnostic to
    which uid it runs at, exactly like `write_root_owned_json` does; it is
    the ELEVATION around the call, not this call, that makes the
    difference.

    The property that boundary protects is MUTATION, and only mutation:
    read, list, traverse and execute stay available to the agent uid on
    purpose -- git spawns `pre-commit`/`commit-msg`/`pre-push` at the AGENT
    uid, from the worker's own `git commit`/`git push`, so the root-owned
    hook is installed 0o555 inside a root-owned 0o755 directory precisely so
    the agent can still read and run it. A layout that denied reading would
    disable the gate rather than protect it, which is why the guard tests
    assert BOTH halves rather than only checking write bits:
    `tests/test_commit_scan_hooks_docker.py`'s real-container, dropped-uid
    probe requires every mutation (`open`-for-write, `chmod`, `unlink`,
    `rename`, `replace`, create-inside, on the hook, the directory and every
    ancestor to the container root) to be refused EACCES/EPERM *and*
    `hook:read`/`dir:listdir` to keep succeeding, and
    `tests/test_commit_scan_engine_boundary.py` pins the other-class
    permission bits (`r-x`, never `w`) plus a real agent-uid probe of this
    directory's own root-owned parent.

    `base_sha` is the boundary base the engine just read (`head_before`);
    it is written next to the hooks as `scan-base` so a first push to a
    remote that has no such ref yet still scans exactly "the commits this
    run created" and not the whole of history. It is a SHA, never a secret.
    `commit-msg`/`pre-commit` never read it -- they scan a single
    not-yet-committed blob of text, not a commit range.

    `secrets` (defaults to `redact.live_redaction_map()`, this ENGINE
    process's own live map, read right now, before the worker is spawned)
    is snapshotted into `KNOWN_SECRETS_FILENAME`/`KNOWN_SECRETS_PEPPER_FILENAME`
    as KEYED HASHES only, never the raw values, 0o644 (root-owned but
    agent-readable under the uid boundary), so the `pre-push`
    hook's authoritative bound (task cure-01-01, requirement I.2/DoD 9) does
    not depend on whatever environment the `git push` that triggers it
    happens to run with, and does not put a secret value anywhere on disk
    -- see `KNOWN_SECRETS_FILENAME`'s own comment for both the why and the
    hashed shape.

    Returns the `pre-push` hook's path (the historical return value, task
    029's own callers key off it), or `None` when the repository's config
    could not be written (no `git`, not a repository) -- the same
    advisory-read posture the rest of this module keeps; the task-boundary
    scan still runs either way.
    """
    hooks_dir = Path(hooks_dir)
    hooks_dir.mkdir(parents=True, exist_ok=True)
    os.chmod(hooks_dir, 0o755)
    pkg_parent = str(Path(__file__).resolve().parents[2])
    python = python or sys.executable
    # Task cure-01-03 (PRD requirement I.3, DoD 9, #210): where a
    # `commit-msg`/`pre-commit` refusal leaves its marker for the engine to
    # pick up -- defaults to `hooks_dir` for callers that never pass one
    # (this module's own pre-cure-01-03 tests, none of which exercise the
    # marker at all), but production always passes the run directory, which
    # stays agent-writable under the real uid boundary while `hooks_dir`
    # itself does not.
    hit_marker_dir = hit_marker_dir if hit_marker_dir is not None else hooks_dir
    push_hook = None
    for name in _ALL_HOOK_NAMES:
        path = hooks_dir / name
        # Replace, never write through: the installed file carries no write
        # bit (0o555 below), so `write_text` on an existing one would be
        # refused for the engine too -- which is the point.
        path.unlink(missing_ok=True)
        path.write_text(_hook_script(name, python, pkg_parent, hit_marker_dir))
        os.chmod(path, 0o555)
        if name == PUSH_GATE_HOOK_NAME:
            push_hook = path
    base_file = hooks_dir / SCAN_BASE_FILENAME
    base_file.unlink(missing_ok=True)
    base_file.write_text(f"{base_sha or ''}\n")
    os.chmod(base_file, 0o444)
    if secrets is None:
        secrets = redact.live_redaction_map()
    pepper = _new_pepper()
    pepper_file = hooks_dir / KNOWN_SECRETS_PEPPER_FILENAME
    pepper_file.unlink(missing_ok=True)
    pepper_file.write_bytes(pepper)
    # 0o644, not 0o600: under the uid boundary (task cure-01-02, requirement
    # I.1/DoD 9) this directory and everything in it is root-owned, but the
    # `pre-push` hook process that reads this file back runs at the AGENT
    # uid (git spawns it from the worker's own shell) -- it must still be
    # able to read the pepper to re-derive the keyed digests. Read access
    # was never the property being protected (a keyed HMAC digest plus its
    # own pepper leaks nothing about a secret's VALUE); only write is, and
    # 0o644 carries no write bit for anyone but the owner.
    os.chmod(pepper_file, 0o644)
    digests_file = hooks_dir / KNOWN_SECRETS_FILENAME
    digests_file.unlink(missing_ok=True)
    digests_file.write_text(json.dumps(_digest_snapshot(pepper, secrets or {})))
    os.chmod(digests_file, 0o644)
    # Task cure-01-01-2 (review finding R2, upheld cure-01-02): under the
    # real uid boundary this whole function runs at effective uid 0 (via
    # `privsep.root_for_write()`, the caller's own elevation) against a
    # WORKSPACE the agent uid owns -- a mismatch git's own "detected
    # dubious ownership" safety check refuses by default (>= 2.35.2)
    # unless the mismatched path is named in `safe.directory`. Detected
    # here, from the plain filesystem stat, rather than assumed from
    # `privsep.separated()`, so this stays true for any caller with a
    # euid/owner mismatch, boundary or not, and stays a no-op (no
    # `safe.directory` at all) for the ordinary same-uid case every
    # non-docker test exercises.
    try:
        ws_owner = os.stat(workspace)
        safe_dir = (str(workspace)
                   if ws_owner.st_uid != os.geteuid() else None)
    except OSError:
        ws_owner = None
        safe_dir = None
    result = _run_git(workspace, "config", "core.hooksPath", str(hooks_dir),
                      safe_directory=safe_dir)
    if result is None or result.returncode != 0:
        return None
    if safe_dir is not None and ws_owner is not None:
        # The write above ran at the ELEVATED euid and therefore replaced
        # `.git/config` outright (git's own lock-file-then-rename write
        # path) with a file owned by THAT euid, never by the workspace's
        # own uid -- a directory-entry rename inherits the writer's
        # identity, not the replaced file's. Left alone, the next call the
        # WORKSPACE's own uid makes that needs to WRITE local git config
        # (`git remote add`, a local `credential.helper`, both of which
        # the workspace-owning uid must still be able to do after this
        # install, task 031/I.1's own commit/push path depends on it)
        # would be refused by the very permission bits this task is
        # protecting elsewhere. Restore the workspace's own ownership on
        # exactly that one file, still inside the caller's elevated
        # window, so installing (or refreshing) the gate never narrows
        # what the workspace's own uid can still do inside its own repo.
        gitdir_result = _run_git(workspace, "rev-parse", "--git-dir",
                                 safe_directory=safe_dir)
        if gitdir_result is not None and gitdir_result.returncode == 0:
            git_dir_str = gitdir_result.stdout.strip()
            if git_dir_str:
                git_dir = Path(git_dir_str)
                if not git_dir.is_absolute():
                    git_dir = Path(workspace) / git_dir
                try:
                    os.chown(git_dir / "config", ws_owner.st_uid,
                             ws_owner.st_gid)
                except OSError:
                    pass
    return push_hook


def _base_from(hooks_dir: str | None) -> str | None:
    env_base = os.environ.get(BASE_ENV_VAR, "").strip()
    if env_base:
        return env_base
    if not hooks_dir:
        return None
    try:
        return (Path(hooks_dir) / SCAN_BASE_FILENAME).read_text().strip() or None
    except OSError:
        return None


def _hashed_snapshot_from(hooks_dir: str | None) -> tuple[bytes | None, dict[str, dict[str, str]]]:
    """The engine's own keyed-hash snapshot of `redact.live_redaction_map()`
    (never the raw values -- see `KNOWN_SECRETS_FILENAME`'s comment), taken
    by `install_push_gate` at install time and read back here regardless of
    whatever environment the `git push` that triggered this hook process
    happens to carry. `(None, {})` on any read failure -- missing file,
    unreadable, malformed JSON -- so a hook process that cannot read its
    own snapshot still falls back to whatever `build_redaction_map()` can
    see from its own environment rather than raising out of the hook.
    """
    if not hooks_dir:
        return None, {}
    try:
        pepper = (Path(hooks_dir) / KNOWN_SECRETS_PEPPER_FILENAME).read_bytes()
    except OSError:
        return None, {}
    try:
        raw = (Path(hooks_dir) / KNOWN_SECRETS_FILENAME).read_text()
        loaded = json.loads(raw)
    except (OSError, ValueError):
        loaded = {}
    return pepper, (loaded if isinstance(loaded, dict) else {})


def _toplevel(default: Path) -> Path:
    result = _run_git(default, "rev-parse", "--show-toplevel")
    if result is None or result.returncode != 0:
        return default
    top = result.stdout.strip()
    return Path(top) if top else default


def hook_main(argv: list[str] | None = None, stdin=None) -> int:
    """The generated hooks' own entry point (`python -m
    ralphd.engine.commit_scan <mode> --hooks-dir <dir> ...`), `<mode>` one
    of `pre-push`, `commit-msg`, `pre-commit` -- the first positional arg,
    which is also each hook's own filename (`_ALL_HOOK_NAMES`).

    Rebuilds the redaction map in THIS process (`build_redaction_map`) for
    every mode, and for the `pre-push` mode ALSO checks a keyed-hash
    fallback (`_hashed_snapshot_from`/`KNOWN_SECRETS_FILENAME`) -- the
    authoritative one (task cure-01-01, PRD requirement I.2, DoD 9): a hook
    process's own environment is whatever the `git push` that triggered it
    happened to carry, which a worker's own shell can strip a secret's env
    var from before pushing, while the value is still live in the ENGINE's
    process. The fallback never hands the hook a raw value -- only
    digests, keyed with a random per-install pepper, both 0o644 (agent-
    readable, never agent-writable) and never printed -- so a hook file
    or an argv carrying secret VALUES is still
    never how this closes the gap. `commit-msg`/`pre-commit` stay
    rebuild-only (a narrower, earlier catch, task 031/requirement I.1) and
    never consult the snapshot. Exit 1 (git refuses the commit or the
    push) on a hit, printing a refusal that names the variable NAME only
    -- never the matched value. Exit 0 on no hit, on an unrecognised mode,
    and on any read it could not complete (fail open; the task boundary is
    still the authoritative record either way).
    """
    argv = list(sys.argv[1:] if argv is None else argv)
    if not argv:
        return 0
    mode, rest = argv[0], list(argv[1:])
    hooks_dir = None
    if "--hooks-dir" in rest:
        i = rest.index("--hooks-dir")
        if i + 1 < len(rest):
            hooks_dir = rest[i + 1]
            del rest[i:i + 2]
    hit_marker_dir = hooks_dir
    if "--hit-marker-dir" in rest:
        i = rest.index("--hit-marker-dir")
        if i + 1 < len(rest):
            hit_marker_dir = rest[i + 1]
            del rest[i:i + 2]
    workspace = _toplevel(Path.cwd())
    base_sha = _base_from(hooks_dir)

    if mode == PUSH_GATE_HOOK_NAME:
        stream = sys.stdin if stdin is None else stdin
        try:
            lines = stream.read().splitlines()
        except (OSError, ValueError):
            return 0
        hit = gate_push_refs(workspace, lines, base_sha=base_sha)
        if hit is None:
            pepper, digests = _hashed_snapshot_from(hooks_dir)
            if pepper is not None and digests:
                for raw in lines:
                    parts = str(raw).split()
                    if len(parts) < 4:
                        continue
                    _local_ref, local_sha, _remote_ref, remote_sha = parts[:4]
                    if not local_sha or set(local_sha) == _ZERO_SHA_CHARS:
                        continue
                    hit = scan_commits_for_hashed_secrets(
                        workspace,
                        _scan_base(workspace, remote_sha, local_sha, base_sha),
                        local_sha, pepper, digests)
                    if hit is not None:
                        break
        if hit is None:
            return 0
        print(refusal_text(hit), file=sys.stderr)
        return 1

    if mode == COMMIT_MSG_HOOK_NAME:
        # git's own arg to `commit-msg`: the path of the file holding the
        # message the agent is about to commit.
        if not rest:
            return 0
        try:
            text = Path(rest[0]).read_text()
        except OSError:
            return 0
        hit = scan_text_for_secrets(text, part="message")
        if hit is None:
            return 0
        if hit_marker_dir:
            _write_hook_hit_marker(hit_marker_dir, mode, hit)
        print(commit_refusal_text(hit), file=sys.stderr)
        return 1

    if mode == PRE_COMMIT_HOOK_NAME:
        # git's own `pre-commit` passes no args; the content to check is
        # whatever is staged.
        result = _run_git(workspace, "diff", "--cached", "--no-color",
                          "--no-renames")
        diff = result.stdout if result is not None and result.returncode == 0 else ""
        hit = scan_text_for_secrets(diff, part="diff")
        if hit is None:
            return 0
        if hit_marker_dir:
            _write_hook_hit_marker(hit_marker_dir, mode, hit)
        print(commit_refusal_text(hit), file=sys.stderr)
        return 1

    return 0


def push_if_clean(workspace, base_sha: str | None, head_sha: str, *,
                  secrets: dict[str, str] | None = None,
                  remote: str = "origin", branch: str = "main",
                  timeout: float = _GIT_TIMEOUT_S):
    """The task-boundary gate. Scans first; a `git push` subprocess is
    started ONLY when the scan comes back clean -- on a hit, no push
    subprocess is ever started, not with a warning, not with a
    disclosure.

    Returns `(pushed: bool, hit: dict | None, refusal: str | None)`.
    """
    hit = scan_commits_for_secrets(workspace, base_sha, head_sha, secrets=secrets)
    if hit is not None:
        return False, hit, refusal_text(hit)
    subprocess.run(
        ["git", "-C", str(workspace), "push", remote, branch],
        capture_output=True, text=True, timeout=timeout)
    return True, None, None


if __name__ == "__main__":  # pragma: no cover - exercised as a real hook
    raise SystemExit(hook_main())
